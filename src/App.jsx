function AdminApp() {
  const [authenticated, setAuthenticated] = useState(false)

  useEffect(() => {
    const flag = localStorage.getItem('admin_authenticated')
    if (flag === '1') setAuthenticated(true)
  }, [])

  function handleLogout() {
    localStorage.removeItem('admin_authenticated')
    setAuthenticated(false)
    window.location.pathname = '/admin'
  }

  if (!authenticated) {
    return <AdminLogin onAuth={() => setAuthenticated(true)} />
  }

  return <AdminDashboard supabase={supabase} onLogout={handleLogout} />
}

function App() {
  if (typeof window !== 'undefined') {
    const p = window.location.pathname
    // keep admin available at /admin but otherwise default to the user app
    if (p.startsWith('/admin')) return <AdminApp />
    // ensure root and any other path load the user flow
    return <UserApp supabase={supabase} />
  }
  return <UserApp supabase={supabase} />
}

